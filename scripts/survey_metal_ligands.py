#!/usr/bin/env python3
"""Non-protein ligands on the binuclear-centre metals of the heme-copper oxidases (scope check: metal-bound waters and ligands).

``sscna analyze`` counts a water or small molecule bound to a metal as a direct ligand, and the conserved-contact loader skips it. This
script asks how common such ligands are at the heme iron and CuB of the oxidase set and whether the species is the same from structure to
structure, using ``conserved_interactions.load_metal_ligands`` (descriptive; never voted):

    python scripts/survey_metal_ligands.py --structures DIR_OF_MMCIF --features experimental_bnc_features.csv

``--structures`` is a directory of the structures' mmCIF files named ``<entry>.cif`` (extracted from the manuscript package's
``data/structures/experimental_pdb_mmcif.tar.gz``); ``--features`` is the manuscript's ``experimental_bnc_features.csv`` (default: the sibling
checkout's archived package). Writes ``docs/scope_checks/12_oxidase_metal_ligands.md`` and ``12_oxidase_metal_ligands.csv``.
"""
import argparse
import csv
import sys
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from modules import conserved_interactions as ci  # noqa: E402

DEFAULT_FEATURES = ROOT.parent / ("CcO_Meta_Analysis_Manuscript/archive/pan_hco_reproducibility_package_2026-10-24/"
                                  "data/hco_structure_features/experimental_bnc_features.csv")


def site_rows(ligands: pd.DataFrame, feature: dict) -> dict:
    """Ligand rows of the two BNC metals of one feature row: {'Fe': frame, 'CuB': frame}."""
    iron = ligands[(ligands["metal_element"] == "FE") & (ligands["metal_resname"] == feature["heme_component_at_BNC"])
                   & (ligands["metal_number"] == int(feature["heme_residue_number"]))]
    if feature["catalytic_chain"] in set(iron["metal_chain"]):
        iron = iron[iron["metal_chain"] == feature["catalytic_chain"]]
    copper = ligands[(ligands["metal_element"] == "CU") & (ligands["metal_resname"] == feature["Cu_component_at_BNC"])
                     & (ligands["metal_number"] == int(feature["Cu_residue_number"])) & (ligands["metal_chain"] == feature["Cu_chain_at_BNC"])]
    return {"Fe": iron, "CuB": copper}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--structures", required=True)
    parser.add_argument("--features", default=str(DEFAULT_FEATURES))
    parser.add_argument("--out", default="docs/scope_checks")
    args = parser.parse_args(argv)
    features = [r for r in csv.DictReader(open(args.features)) if r["evidence_source"] == "experimental_PDB_observed"]
    cache, rows = {}, []
    sites = Counter()
    species = defaultdict(Counter)
    distances = defaultdict(list)
    for feature in features:
        entry = feature["entry_id"].lower()
        if entry not in cache:
            cache[entry] = ci.load_metal_ligands(Path(args.structures) / f"{entry}.cif", structure_id=entry)
        for site, frame in site_rows(cache[entry], feature).items():
            sites[site] += 1
            for name in sorted(set(frame["ligand_resname"])):
                species[site][name] += 1
            for r in frame.itertuples():
                distances[(site, r.ligand_resname)].append(r.distance)
                rows.append((feature["entry_id"], site, r.ligand_resname, r.ligand_atom, round(r.distance, 3), r.water))
    lines = ["# Non-protein ligands on the heme iron and CuB of the oxidases", "",
             f"Generated by `scripts/survey_metal_ligands.py`. {len(features)} observed binuclear-centre feature rows ({len({f['entry_id'] for f in features})} entries). "
             "A ligand is a heavy atom of a hetero residue or water within 2.8 A of the metal atom, in a residue other than the metal's own "
             "(`conserved_interactions.load_metal_ligands`).", "",
             "| Site | sites | with a non-protein ligand within 2.8 A | species (structures with it; distance range, median) |", "|---|---|---|---|"]
    for site in ("Fe", "CuB"):
        with_ligand = len({(r[0], r[1]) for r in rows if r[1] == site})
        detail = "; ".join(f"{name} {count} ({np.min(distances[(site, name)]):.2f}-{np.max(distances[(site, name)]):.2f} A, median {np.median(distances[(site, name)]):.2f})"
                           for name, count in species[site].most_common())
        lines.append(f"| {site} | {sites[site]} | {with_ligand} ({100 * with_ligand / sites[site]:.0f}%) | {detail} |")
    lines += ["", f"{len({name for site in species for name in species[site]})} different species occur (a species with several atoms within 2.8 A, such as azide or peroxide, "
              "is counted once per structure). The species reflects what was modelled in each experiment (exogenous molecules such as CO, azide, cyanide, NO and thiocyanate; "
              "peroxide- and peroxo-like species; water; hydroxide), so it is reported per structure and not voted. Some rows at CuB are other hetero residues "
              "(a heme or chloride) whose atoms lie within 2.8 A; the table lists every non-protein atom in range, not only chemical ligands.", ""]
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "12_oxidase_metal_ligands.md").write_text("\n".join(lines) + "\n")
    pd.DataFrame(rows, columns=["entry_id", "site", "ligand_resname", "ligand_atom", "distance", "water"]).to_csv(out / "12_oxidase_metal_ligands.csv", index=False)
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
