#!/usr/bin/env python3
"""What each treatment of a small group does to the conserved set, and the per-contact detail of the vote (heme-copper oxidases).

Group C of the oxidase set has exactly the minimum of five voting sequences, so every conserved contact needs all five. This script runs
the vote once with ``conserved_contacts(coverage=True)`` and reports, from its columns, how the conserved set changes if group C is not
required, is allowed one negative sequence, or is read on its own, and which sequences hold contacts back. The headline stays the
manuscript's rule (all groups at 90% with at least five voting sequences); the detail is what a log can carry beside it.

    python scripts/group_options.py        # one vote: about a minute, about 2.5 GB, one process

Writes ``docs/scope_checks/11_group_options.md`` and ``11_group_options_contacts.csv`` (the contacts conserved in A and B1, with their detail).
"""
import os
import sys
from pathlib import Path

import pandas as pd

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from modules import conserved_interactions as ci  # noqa: E402


def treatments(votes: pd.DataFrame, groups) -> dict:
    """Counts for the treatments of the last group, from the coverage columns."""
    last = groups[-1]
    others = [g for g in groups if g != last]
    in_group = {g: votes["conserved_in"].str.split("+").apply(lambda parts, g=g: g in parts) for g in groups}
    required = pd.concat([in_group[g] for g in others], axis=1).all(axis=1)
    one_negative = (votes["failing_groups"] == last) & (votes[f"spare_negatives_{last}"] == -1) & (votes[f"spare_voters_{last}"] >= 0)
    return {"as_is": int(votes["conserved_contact"].sum()), "others_only": int(required.sum()),
            "others_only_not_last": int((required & ~in_group[last]).sum()), "last_one_negative": int(votes["conserved_contact"].sum() + one_negative.sum()),
            "alone": {g: int(in_group[g].sum()) for g in groups}, "last_only": int((in_group[last] & ~required).sum())}


def main():
    import shuffle_control as sc

    controls = Path(os.environ.get("HCO_MANUSCRIPT", ROOT.parent / "CcO_Meta_Analysis_Manuscript/manuscript/controls"))
    data = sc.load_hco(controls)
    groups = data["groups"]
    votes = ci.conserved_contacts(data["atoms"], data["structures"], groups=groups, coverage=True)
    counts = treatments(votes, groups)
    sizes = data["structures"].groupby("group")["sequence_id"].nunique()
    first = data["structures"].sort_values("structure_id").drop_duplicates("sequence_id").set_index("sequence_id")["structure_id"]
    last = groups[-1]
    lines = ["# Group options and per-contact detail of the vote (heme-copper oxidases)", "",
             f"Generated by `scripts/group_options.py`. {len(votes)} candidate pairs; groups " + ", ".join(f"{g} ({sizes[g]} sequences)" for g in groups) +
             f". The rule: in every group at least 90% of at least 5 voting sequences positive. Group {last} has {sizes[last]} sequences, so it passes only if all of them vote positive.", "",
             "## What each treatment of group " + last + " gives", "", "| Treatment | conserved contacts |", "|---|---|",
             f"| As is: all groups required (the manuscript's rule, the headline) | {counts['as_is']} |",
             f"| " + " and ".join(groups[:-1]) + f" required, {last} not | {counts['others_only']} (of which {counts['others_only_not_last']} not conserved in {last}) |",
             f"| All groups required, {last} may have one negative sequence (80%) | {counts['last_one_negative']} |"]
    for g in groups:
        lines.append(f"| {g} on its own | {counts['alone'][g]} |")
    lines += [f"| Conserved in {last} but not in " + " and ".join(groups[:-1]) + f" | {counts['last_only']} |", ""]
    label = votes["conserved_in"].replace("", "(none)").value_counts()
    lines += ["## The groups each candidate pair is conserved in", "", "| conserved_in | pairs |", "|---|---|"] + [f"| {k} | {v} |" for k, v in label.items()] + [""]
    group_of = data["structures"].drop_duplicates("sequence_id").set_index("sequence_id")["group"]
    strict = votes[votes["held_back_by"] != ""]
    away = votes[votes["one_negative_away"] != ""]
    lines += ["## Contacts one negative sequence away", "",
              f"{len(strict)} pairs would pass the rule if one sequence were left out (`held_back_by`: exactly one group fails and the rest of it would still meet "
              f"the minimum of voting sequences). {len(away)} pairs are one negative sequence short of the support in the single group they fail, ignoring the minimum "
              "(`one_negative_away`); by the group they fail in:", "", "| Failing group | pairs one negative away |", "|---|---|"]
    for g, count in away["failing_groups"].value_counts().items():
        lines.append(f"| {g} | {count} |")
    named = away["one_negative_away"].str.split(";").explode().value_counts().head(8)
    lines += ["", "Sequences named most often (first structure of each):", "", "| Sequence (first structure) | group | pairs it alone keeps below the support |", "|---|---|---|"]
    lines += [f"| {first[s]} | {group_of[s]} | {c} |" for s, c in named.items()] + [""]
    conserved = votes[votes["conserved_contact"]]
    lines += ["## Margins of the headline contacts", "", "| Group | contacts with no spare negative vote | contacts at exactly the minimum of voters |", "|---|---|---|"]
    for g in groups:
        lines.append(f"| {g} | {int((conserved[f'spare_negatives_{g}'] == 0).sum())} of {len(conserved)} | {int((conserved[f'spare_voters_{g}'] == 0).sum())} of {len(conserved)} |")
    out = ROOT / "docs/scope_checks"
    (out / "11_group_options.md").write_text("\n".join(lines) + "\n")
    required = votes["conserved_in"].str.split("+").apply(lambda parts: all(g in parts for g in groups[:-1]))
    keep = ["position_a", "position_b", "conserved_in", "failing_groups", "held_back_by"] + [c for g in groups for c in (f"contact_n_{g}", f"contact_{g}", f"spare_negatives_{g}", f"spare_voters_{g}")]
    votes.loc[required, keep].assign(headline=votes.loc[required, "conserved_contact"]).to_csv(out / "11_group_options_contacts.csv", index=False)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
