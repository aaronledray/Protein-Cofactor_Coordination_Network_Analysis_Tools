#!/usr/bin/env python3
"""Background rates of neighbor-contact chemistry (TODO item D): how often residues one apart in sequence touch.

``residue_contacts(neighbor_contacts=True, neighbor_chemistry=NEIGHBOR_CHEMISTRY_ALL)`` reports polar, ionic, hydrophobic and
aromatic contacts between a residue and the next one, judged per atom pair. Whether a conserved neighbor contact is unusual depends on
how often that residue-type pair shows the class anyway, so this script measures that on the atomic-resolution structures fetched by
``survey_sulfur_acceptors.py fetch`` and writes the background table.

    python scripts/survey_neighbor_chemistry.py --cache survey_cache/sulfur --out docs/scope_checks

Outputs ``06_neighbor_chemistry_survey.md`` and ``06_neighbor_chemistry_background.csv`` (one row per residue-type pair: neighbor pairs
counted, and how many show each class). It also reports how often the C-beta atoms of neighbors are within 4 A, which is
conformation and is why C-beta is left out of the hydrophobic and aromatic classes.
"""
import argparse
import json
import sys
import warnings
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from modules import conserved_interactions as ci  # noqa: E402

CLASSES = ci.NEIGHBOR_CHEMISTRY_ALL


def neighbor_pairs(atoms):
    """[(first resname, second resname, cb_cb_distance or None)] for every pair of residues one apart in sequence joined by a peptide bond."""
    rows = []
    heavy = atoms.reset_index(drop=True)
    by_seq = {s: g for s, g in heavy.groupby("seq_index")}
    for s, g in by_seq.items():
        h = by_seq.get(s + 1)
        if h is None:
            continue
        c, n = g[g["atom"] == "C"], h[h["atom"] == "N"]
        if c.empty or n.empty or np.linalg.norm(c[["x", "y", "z"]].to_numpy(float)[0] - n[["x", "y", "z"]].to_numpy(float)[0]) >= 1.6:
            continue
        cb1, cb2 = g[g["atom"] == "CB"], h[h["atom"] == "CB"]
        cb = float(np.linalg.norm(cb1[["x", "y", "z"]].to_numpy(float)[0] - cb2[["x", "y", "z"]].to_numpy(float)[0])) if len(cb1) and len(cb2) else None
        rows.append((g["resname"].iloc[0], h["resname"].iloc[0], cb))
    return rows


def excluded_adjacency(atoms):
    """Residue pairs with the generic adjacencies the neighbor classes leave out: (ring atom within 4 A of the neighbor's backbone or C-beta, C-beta pair within 4 A)."""
    frame = atoms.reset_index(drop=True)
    xyz = frame[["x", "y", "z"]].to_numpy(float)
    name, res = frame["atom"].to_numpy(), frame["resname"].str.upper().to_numpy()
    seq, pos = frame["seq_index"].to_numpy(), frame["position"].to_numpy()
    backbone_or_cb = np.array([n in ci.BACKBONE or n == "CB" for n in name])
    ring = np.array([n in ci.RING_ATOMS.get(r, ()) for n, r in zip(name, res)])
    i, j, d = ci._close_pairs(xyz, xyz, 4.0)
    adjacent = (i < j) & (pos[i] != pos[j]) & (np.abs(seq[i] - seq[j]) == 1)
    ring_vs_backbone = adjacent & ((ring[i] & backbone_or_cb[j]) | (ring[j] & backbone_or_cb[i]))
    cb_cb = adjacent & (name[i] == "CB") & (name[j] == "CB")
    bb = np.array([n in ci.BACKBONE for n in name])
    ring_pairs = set()
    if ring_vs_backbone.any():
        keep_i, keep_j = ci._neighbor_atom_pairs(xyz, pos, seq, name, bb, ring_vs_backbone, i, j)
        ring_pairs = {(min(pos[a], pos[b]), max(pos[a], pos[b])) for a, b in zip(keep_i, keep_j)}
    cb_pairs = {(min(pos[a], pos[b]), max(pos[a], pos[b])) for a, b in zip(i[cb_cb], j[cb_cb])}
    return len(ring_pairs), len(cb_pairs)


def structure_job(args):
    path, chain, sid = args
    warnings.filterwarnings("ignore")
    try:
        atoms = ci.load_atoms(path, chain, structure_id=sid)
        pairs = neighbor_pairs(atoms)
        rows = ci.residue_contacts(atoms, neighbor_contacts=True, neighbor_chemistry=CLASSES)
        generic = excluded_adjacency(atoms)
    except Exception:
        return [], [], (0, 0)
    rows = rows[rows["neighbor"].astype(bool)]            # astype: an empty frame has object-typed columns
    keep = ["resname_a", "resname_b", "min_distance", "closest", *CLASSES]
    return pairs, rows[keep].to_dict("records"), generic


def report(denominators, found, n_structures, generic):
    total = len(denominators)
    frame = pd.DataFrame(found)
    lines = ["# Background rates of neighbor-contact chemistry (PDB survey)", "",
             f"Generated by `scripts/survey_neighbor_chemistry.py` for TODO item D. {n_structures} atomic-resolution X-ray structures (one per 30% "
             f"sequence cluster, 1.2 A or better, first chain); {total} pairs of residues one apart in sequence and joined by a peptide bond. "
             "Classes are those of `residue_contacts(neighbor_contacts=True, neighbor_chemistry=NEIGHBOR_CHEMISTRY_ALL)`: an atom pair at "
             "least 4 bonds apart through the peptide bond that is `polar` (a hydrogen bond with one side-chain atom: donor to acceptor within 3.5 A, and where "
             "the donor's hydrogen can be placed it must point at the acceptor), `ionic`, `hydrophobic` "
             "(C/S pair, both atoms beyond C-beta, within 4.0 A) or `aromatic` (a ring atom against a side-chain atom beyond C-beta, within 4.0 A).", "",
             "| Class | neighbor pairs with the class | percent of neighbor pairs |", "|---|---|---|"]
    for name in CLASSES:
        count = int(frame[name].sum()) if len(frame) else 0
        lines.append(f"| {name} | {count} | {100 * count / total:.2f} |")
    lines += ["", f"Neighbor pairs with at least one qualifying atom pair: {len(frame)} ({100 * len(frame) / total:.2f}%), "
              f"which is {100 * len(frame) / (total + n_structures):.1f} rows per 100 residues."]
    cb = np.array([d for _, _, d in denominators if d is not None])
    aromatic = sum(1 for a, b, _ in denominators if a in ci.RING_ATOMS or b in ci.RING_ATOMS)
    ring_backbone, cb_pairs = generic
    both_aromatic = int(frame["aromatic"].sum()) if len(frame) else 0
    lines += ["", "## What the neighbor classes leave out, and how much", "",
              f"- C-beta against C-beta: the C-beta atoms of neighbors are within 4.0 A in {100 * np.mean(cb <= 4.0):.2f}% of {len(cb)} pairs and "
              f"within 4.5 A in {100 * np.mean(cb <= 4.5):.2f}%, so leaving C-beta out of the hydrophobic class costs almost nothing and is a principle "
              "(the C-beta position follows from the backbone), not a large correction.",
              f"- A ring atom within 4.0 A of the neighbor's backbone or C-beta (at least 4 bonds apart): {ring_backbone} residue pairs, "
              f"{100 * ring_backbone / aromatic:.1f}% of the {aromatic} neighbor pairs that include a Phe, Tyr, Trp or His; the `aromatic` class "
              f"(ring against a side-chain atom beyond C-beta) fires in {both_aromatic} pairs. A ring sits beside the next backbone almost by construction, "
              "so counting that adjacency would mark every aromatic residue; the classes count only ring-to-side-chain contacts."]
    base = pd.DataFrame(denominators, columns=["resname_a", "resname_b", "cb"]).groupby(["resname_a", "resname_b"]).size().rename("n_pairs").reset_index()
    if len(frame):
        counts = frame.groupby(["resname_a", "resname_b"])[list(CLASSES)].sum().reset_index()
        base = base.merge(counts, on=["resname_a", "resname_b"], how="left").fillna(0)
    for name in CLASSES:
        base[f"{name}_rate"] = (base.get(name, 0) / base["n_pairs"]).round(4)
    for name in ("hydrophobic", "aromatic", "polar"):
        top = base[base["n_pairs"] >= 200].sort_values(f"{name}_rate", ascending=False).head(8)
        lines += ["", f"## Residue-type pairs with the highest `{name}` rate (at least 200 pairs)", "", "| First | Second | pairs | with class | percent |", "|---|---|---|---|---|"]
        for r in top.itertuples():
            lines.append(f"| {r.resname_a.title()} | {r.resname_b.title()} | {int(r.n_pairs)} | {int(getattr(r, name))} | {100 * getattr(r, f'{name}_rate'):.1f} |")
    lines += ["", "How to use it: a conserved neighbor contact of a residue-type pair whose background rate is high (for example Ile followed by Pro, 47%, for "
              "hydrophobic) says little; one with a low background rate is unusual. The per-pair table is `06_neighbor_chemistry_background.csv`.",
              "", "Caveats: atomic-resolution structures are small, well-ordered proteins; one chain per cluster; first model."]
    return "\n".join(lines) + "\n", base


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--cache", default="survey_cache/sulfur")
    parser.add_argument("--out", default="docs/scope_checks")
    args = parser.parse_args(argv)
    cache = Path(args.cache)
    chains = json.loads((cache / "chains.json").read_text())["chains"]
    jobs = [(cache / f"{entry}.cif", chain, entry) for entry, chain in sorted(chains.items()) if (cache / f"{entry}.cif").exists()]
    with Pool(8) as pool:
        results = pool.map(structure_job, jobs, chunksize=4)
    denominators = [p for pairs, _, _ in results for p in pairs]
    found = [r for _, rows, _ in results for r in rows]
    generic = (sum(g[0] for _, _, g in results), sum(g[1] for _, _, g in results))
    text, base = report(denominators, found, len(jobs), generic)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "06_neighbor_chemistry_survey.md").write_text(text)
    base.to_csv(out / "06_neighbor_chemistry_background.csv", index=False)
    print(f"{len(jobs)} structures, {len(denominators)} neighbor pairs, {len(found)} rows -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
