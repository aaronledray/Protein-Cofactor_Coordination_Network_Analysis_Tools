#!/usr/bin/env python3
"""How much does the sequence-neighbor rule hide? Side-chain acceptors of backbone N-H bonds, by sequence offset.

Evidence for TODO item D (docs/scope_checks/05_sequence_neighbors_survey.md). ``residue_contacts`` leaves out residue
pairs closer than ``min_separation`` (2) in sequence, so a contact between residue i and residue i+1 or i-1 is never
reported. This script uses the atomic-resolution structures already fetched by ``survey_sulfur_acceptors.py fetch``
and counts, for each residue type, how often a side-chain oxygen or nitrogen accepts a hydrogen bond from the backbone
N-H of the residue at each offset (-2 to +4). Offsets of one are hidden by the rule; the others are listed. The amide
hydrogen is placed from the backbone, and a bond is counted when H...A <= 2.5 A, the N-H...A angle is at least 120 degrees
and N...A <= 3.5 A (the defaults of ``modules.protonation.directional_hbonds``).

    python scripts/survey_sequence_neighbors.py --cache survey_cache/sulfur --out docs/scope_checks
"""
import argparse
import json
import sys
import warnings
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from modules.protonation import backbone_amide_hydrogen, hydrogen_bond_geometry  # noqa: E402

ACCEPTORS = {"ASP": ("OD1", "OD2"), "GLU": ("OE1", "OE2"), "ASN": ("OD1",), "GLN": ("OE1",), "SER": ("OG",), "THR": ("OG1",), "TYR": ("OH",),
             "HIS": ("ND1", "NE2")}
OFFSETS = (-2, -1, 1, 2, 3, 4)
H_ACCEPTOR_MAX, ANGLE_MIN, DONOR_ACCEPTOR_MAX = 2.5, 120.0, 3.5


def side_chain_hydrogen_bonds(path, chain_id):
    """One dict per residue with an acceptor listed in ``ACCEPTORS``: ``bonds`` = the offsets whose backbone N-H it accepts from."""
    from Bio.PDB import MMCIFParser

    warnings.filterwarnings("ignore")
    model = MMCIFParser(QUIET=True).get_structure("x", str(path))[0]
    if chain_id not in model:
        return []
    residues = [r for r in model[chain_id] if r.id[0] == " "]
    index, previous, order = {}, None, 0
    for r in residues:                                              # sequence index from the numbering, as load_atoms does
        number = int(r.id[1])
        order += 1 if previous is None or number <= previous else number - previous
        previous = number
        index[order] = r
    amide_h = {}                                                    # order -> (N, H) for residues whose amide hydrogen can be placed
    for order, r in index.items():
        before = index.get(order - 1)
        if before is not None and all(a in r for a in ("N", "CA")) and "C" in before and r.resname != "PRO" \
                and np.linalg.norm(before["C"].coord - r["N"].coord) < 1.6:
            amide_h[order] = (r["N"].coord, backbone_amide_hydrogen(r["N"].coord, before["C"].coord, r["CA"].coord))
    rows = []
    for order, r in index.items():
        names = [n for n in ACCEPTORS.get(r.resname, ()) if n in r]
        if not names:
            continue
        bonds = set()
        for offset in OFFSETS:
            if order + offset not in amide_h:
                continue
            n, h = amide_h[order + offset]
            for name in names:
                acceptor = r[name].coord
                h_a, angle = hydrogen_bond_geometry(h, n, acceptor)
                if h_a <= H_ACCEPTOR_MAX and angle >= ANGLE_MIN and np.linalg.norm(n - acceptor) <= DONOR_ACCEPTOR_MAX:
                    bonds.add(offset)
        placeable = [offset for offset in OFFSETS if order + offset in amide_h]
        rows.append({"pdb": Path(path).stem[:4].upper(), "resname": r.resname, "bonds": sorted(bonds), "placeable": placeable})
    return rows


def _job(args):
    return side_chain_hydrogen_bonds(*args)


def report(frame, n_structures):
    lines = ["# Side-chain acceptors of backbone N-H bonds, by sequence offset (PDB survey)", "",
             f"Generated by `scripts/survey_sequence_neighbors.py` for TODO item D. {n_structures} atomic-resolution X-ray structures "
             f"(one per 30% sequence cluster, 1.2 A or better, first chain); {len(frame)} residues with a side-chain acceptor "
             f"(Asp, Glu, Asn, Gln, Ser, Thr, Tyr, His). Amide hydrogens are placed from the backbone; a bond is H...A <= {H_ACCEPTOR_MAX} A, "
             f"N-H...A >= {ANGLE_MIN:g} degrees, N...A <= {DONOR_ACCEPTOR_MAX} A. Offset +1 is the next residue's N-H. "
             "`residue_contacts` hides offsets of 1 (`min_separation=2`) and lists the others.", "",
             "Cells: percent of residues of that type that accept a bond from the N-H at that offset (residues whose N-H could be placed).", "",
             "| Residue | n | -2 | **-1** | **+1** | +2 | +3 | +4 | any hidden (+-1) | any listed (+-2 to +4) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for resname in ("ASP", "ASN", "SER", "THR", "GLU", "GLN", "TYR", "HIS"):
        sub = frame[frame["resname"] == resname]
        cells = []
        for offset in OFFSETS:
            usable = sub[sub["placeable"].apply(lambda p: offset in p)]
            cells.append(f"{100 * usable['bonds'].apply(lambda b: offset in b).mean():.1f}" if len(usable) else "-")
        hidden = sub["bonds"].apply(lambda b: any(o in b for o in (-1, 1))).mean()
        listed = sub["bonds"].apply(lambda b: any(o in b for o in (-2, 2, 3, 4))).mean()
        lines.append(f"| {resname.title()} | {len(sub)} | " + " | ".join(cells[:2]) + " | " + " | ".join(cells[2:]) + f" | {100 * hidden:.1f} | {100 * listed:.1f} |")
    total = sum(len(b) for b in frame["bonds"])
    hidden_total = sum(sum(1 for o in b if abs(o) == 1) for b in frame["bonds"])
    lines += ["", f"Of {total} side-chain-acceptor / backbone-N-H bonds found at these offsets, {hidden_total} ({100 * hidden_total / total:.1f}%) are to a "
              "neighbor at offset +-1, which `residue_contacts` cannot report.", "",
              "Caveats: the hydrogen is placed, not observed; only the listed side-chain acceptors are counted (not backbone C=O, "
              "not side-chain donors to backbone O); a bond to the residue's own backbone N-H is a different pair and is excluded by offset 0."]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--cache", default="survey_cache/sulfur")
    parser.add_argument("--out", default="docs/scope_checks")
    args = parser.parse_args(argv)
    cache = Path(args.cache)
    chains = json.loads((cache / "chains.json").read_text())["chains"]
    jobs = [(cache / f"{entry}.cif", chain) for entry, chain in sorted(chains.items()) if (cache / f"{entry}.cif").exists()]
    with Pool(8) as pool:
        results = pool.map(_job, jobs, chunksize=8)
    frame = pd.DataFrame([row for result in results for row in result])
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "05_sequence_neighbors_survey.md").write_text(report(frame, len(jobs)))
    print(f"{len(jobs)} structures, {len(frame)} residues -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
